export function localizeServices(services: Service[], locale: Locale): Service[] {
  if (locale === "en") return services;
  const names = locale === "pt" ? ptNames : esNames;
  const text = locale === "pt" ? ptText : esText;
  return services.map((service) => ({
    ...service,
    displayName: names[service.displayName] ?? service.displayName,
    description: service.description ? (text[service.description] ?? service.description) : undefined,
    details: service.details?.map((detail) => text[detail] ?? detail),
  }));
}
